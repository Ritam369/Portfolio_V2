export default function LinkItem({ label, value, url, icon }) {
  const isExternal = url.startsWith('http') || url.startsWith('mailto')

  const inner = (
    <div className="flex items-center justify-between px-4 py-3.5 border-b border-border-subtle last:border-b-0 group hover:bg-[#161616] transition-colors duration-150">
      <div className="flex items-center gap-3">
        <span className="text-accent shrink-0"><Icon name={icon} /></span>
        <div>
          <p className="text-text-primary text-sm font-medium group-hover:text-accent transition-colors duration-150">{label}</p>
          {value && <p className="text-text-muted text-xs mt-0.5">{value}</p>}
        </div>
      </div>
      <span className="text-text-muted group-hover:text-text-primary transition-colors duration-150">
        <ExternalIcon />
      </span>
    </div>
  )

  return isExternal
    ? <a href={url} target="_blank" rel="noopener noreferrer">{inner}</a>
    : <a href={url}>{inner}</a>
}
